/**
 * The resolved app theme (light or dark); lets assets like the brand logo pick
 * the variant that contrasts with the current background.
 */
val LocalIsDarkTheme = staticCompositionLocalOf { false }

/**
 * The app-wide Material 3 theme; wrap the whole UI in this exactly once, in
 * [fr.gshz.hideandseek.MainActivity].
 *
 * Dynamic color is intentionally disabled: the "Wayfinding" brand must look the same on every
 * device regardless of the user's wallpaper.
 */
@Composable
fun AppTheme(
    themeMode: String = "system",
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        "light" -> false
        "dark" -> true
        else -> isSystemInDarkTheme()
    }
    CompositionLocalProvider(
        LocalIsDarkTheme provides darkTheme,
        LocalExtendedColors provides if (darkTheme) DarkExtendedColors else LightExtendedColors,
    ) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
            typography = Typography,
            shapes = Shapes,
            content = content,
        )
    }
}
